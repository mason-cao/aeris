"""Lossless export, verification, and restore of expert labels.

Labels are the one irreplaceable output of this study. They are hours of expert
time, they cannot be regenerated by rerunning anything, and as of 2026-08-10
they live in a single Docker volume. Everything else in the pipeline is
reproducible from a hashed input; this is not.

The export keeps every column, so a restore reproduces the rows rather than an
approximation of them. ``analysis_export`` is not a substitute: it deliberately
narrows each label to (labeler, claim_id, verdict) and drops notes, the
presentation index, and the free-text cause.

CLI:
  python -m app.eval.label_backup export --output labels-20260810.json
  python -m app.eval.label_backup verify --input labels-20260810.json
  python -m app.eval.label_backup restore --input labels-20260810.json --confirm
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
import tempfile
import uuid
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, NoReturn

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import ExpertLabel

SCHEMA_VERSION = 1


class LabelBackupError(ValueError):
    """Raised when an export, verification, or restore is not admissible."""


def _canonical_json(value: object) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def payload_sha256(labels: Sequence[Mapping[str, Any]]) -> str:
    """Checksum the label rows alone, so provenance fields cannot mask a change."""
    return hashlib.sha256(_canonical_json(list(labels)).encode("utf-8")).hexdigest()


def _serialize(label: ExpertLabel) -> dict[str, Any]:
    created_at = label.created_at
    if created_at is not None and created_at.tzinfo is None:
        # SQLite hands back naive datetimes; the column is timezone-aware.
        created_at = created_at.replace(tzinfo=UTC)
    return {
        "id": str(label.id),
        "anomaly_id": str(label.anomaly_id),
        "labeler": label.labeler,
        "true_cause": label.true_cause,
        "claim_validations_json": label.claim_validations_json,
        "created_at": created_at.isoformat() if created_at is not None else None,
    }


async def build_export(session: AsyncSession) -> dict[str, Any]:
    """Read every expert label into a deterministic, checksummed payload."""
    rows = (
        (await session.execute(select(ExpertLabel).order_by(ExpertLabel.id)))
        .scalars()
        .all()
    )
    labels = sorted(
        (_serialize(row) for row in rows),
        key=lambda row: (row["labeler"], row["anomaly_id"]),
    )
    verdict_counts: dict[str, int] = {}
    for label in labels:
        for validation in label["claim_validations_json"] or []:
            verdict = validation.get("verdict")
            key = "missing" if verdict is None else str(verdict)
            verdict_counts[key] = verdict_counts.get(key, 0) + 1
    return {
        "schema_version": SCHEMA_VERSION,
        "label_count": len(labels),
        "labeler_counts": {
            labeler: sum(1 for row in labels if row["labeler"] == labeler)
            for labeler in sorted({row["labeler"] for row in labels})
        },
        "claim_verdict_counts": dict(sorted(verdict_counts.items())),
        "payload_sha256": payload_sha256(labels),
        "labels": labels,
    }


def _validated_export(payload: object) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    if not isinstance(payload, dict):
        raise LabelBackupError("export root must be an object")
    if payload.get("schema_version") != SCHEMA_VERSION:
        raise LabelBackupError(f"export schema_version must equal {SCHEMA_VERSION}")
    labels = payload.get("labels")
    if not isinstance(labels, list):
        raise LabelBackupError("export labels must be an array")

    seen: set[tuple[str, str]] = set()
    for position, label in enumerate(labels, start=1):
        if not isinstance(label, dict):
            raise LabelBackupError(f"label {position} must be an object")
        for field in ("id", "anomaly_id", "labeler"):
            value = label.get(field)
            if not isinstance(value, str) or not value.strip():
                raise LabelBackupError(
                    f"label {position} field {field} must be a nonempty string"
                )
        for field in ("id", "anomaly_id"):
            try:
                uuid.UUID(str(label[field]))
            except ValueError as exc:
                raise LabelBackupError(
                    f"label {position} field {field} is not a UUID"
                ) from exc
        key = (str(label["labeler"]), str(label["anomaly_id"]))
        if key in seen:
            raise LabelBackupError(
                f"duplicate label for {key[0]} on anomaly {key[1]}"
            )
        seen.add(key)

    expected = payload.get("payload_sha256")
    actual = payload_sha256(labels)
    if expected != actual:
        raise LabelBackupError(
            f"export checksum mismatch: recorded {expected}, recomputed {actual}"
        )
    if payload.get("label_count") != len(labels):
        raise LabelBackupError(
            f"export label_count {payload.get('label_count')} disagrees with "
            f"{len(labels)} label rows"
        )
    return payload, labels


def load_export(path: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Read an export and refuse it unless it is internally consistent."""
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise LabelBackupError(f"cannot read export {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise LabelBackupError(f"invalid JSON in export {path}: {exc}") from exc
    return _validated_export(payload)


async def verify_export(
    session: AsyncSession, payload: Mapping[str, Any]
) -> dict[str, Any]:
    """Compare a stored export against the live database, row for row."""
    _validated_export(dict(payload))
    live = await build_export(session)
    stored_labels = list(payload["labels"])
    live_labels = live["labels"]

    stored_keys = {(row["labeler"], row["anomaly_id"]) for row in stored_labels}
    live_keys = {(row["labeler"], row["anomaly_id"]) for row in live_labels}
    stored_index = {(row["labeler"], row["anomaly_id"]): row for row in stored_labels}
    live_index = {(row["labeler"], row["anomaly_id"]): row for row in live_labels}
    differing = sorted(
        f"{labeler}/{anomaly_id}"
        for labeler, anomaly_id in stored_keys & live_keys
        if stored_index[(labeler, anomaly_id)] != live_index[(labeler, anomaly_id)]
    )
    return {
        "matches": (
            payload["payload_sha256"] == live["payload_sha256"] and not differing
        ),
        "export_sha256": payload["payload_sha256"],
        "live_sha256": live["payload_sha256"],
        "only_in_export": sorted(f"{a}/{b}" for a, b in stored_keys - live_keys),
        "only_in_database": sorted(f"{a}/{b}" for a, b in live_keys - stored_keys),
        "differing_rows": differing,
    }


async def restore_export(
    session: AsyncSession, labels: Sequence[Mapping[str, Any]]
) -> int:
    """Insert exported labels, refusing rather than overwriting existing work."""
    existing = {
        (labeler, str(anomaly_id))
        for labeler, anomaly_id in (
            await session.execute(
                select(ExpertLabel.labeler, ExpertLabel.anomaly_id)
            )
        ).all()
    }
    collisions = sorted(
        f"{label['labeler']}/{label['anomaly_id']}"
        for label in labels
        if (str(label["labeler"]), str(label["anomaly_id"])) in existing
    )
    if collisions:
        raise LabelBackupError(
            "refusing to restore over existing labels: " + ", ".join(collisions)
        )

    for label in labels:
        created_at = label.get("created_at")
        session.add(
            ExpertLabel(
                id=uuid.UUID(str(label["id"])),
                anomaly_id=uuid.UUID(str(label["anomaly_id"])),
                labeler=str(label["labeler"]),
                true_cause=label.get("true_cause"),
                claim_validations_json=label.get("claim_validations_json"),
                created_at=(
                    datetime.fromisoformat(created_at) if created_at else None
                ),
            )
        )
    await session.commit()
    return len(labels)


def write_export(path: Path, payload: Mapping[str, Any]) -> None:
    """Write the export atomically and byte-deterministically."""
    text = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            temporary_path = Path(handle.name)
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_path, path)
        temporary_path = None
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m app.eval.label_backup",
        description="Export, verify, or restore expert labels.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    export = sub.add_parser("export", help="write every expert label to JSON")
    export.add_argument("--output", required=True, type=Path)

    verify = sub.add_parser("verify", help="compare an export against the database")
    verify.add_argument("--input", required=True, type=Path)

    restore = sub.add_parser("restore", help="insert exported labels")
    restore.add_argument("--input", required=True, type=Path)
    restore.add_argument(
        "--confirm",
        action="store_true",
        help="required; restore writes to expert_labels",
    )
    return parser


def _argument_error(parser: argparse.ArgumentParser, message: str) -> NoReturn:
    parser.error(message)


async def _amain(argv: Sequence[str] | None = None) -> int:
    from app.db.session import async_session, engine_lifecycle

    parser = _parser()
    args = parser.parse_args(argv)

    async with engine_lifecycle():
        async with async_session() as session:
            try:
                if args.command == "export":
                    payload = await build_export(session)
                    write_export(args.output, payload)
                    print(
                        f"exported {payload['label_count']} labels "
                        f"({payload['claim_verdict_counts']}) "
                        f"sha256 {payload['payload_sha256']}"
                    )
                    return 0

                if args.command == "verify":
                    payload, _ = load_export(args.input)
                    report = await verify_export(session, payload)
                    if report["matches"]:
                        print(f"verified: export matches {payload['label_count']} live labels")
                        return 0
                    print("MISMATCH " + _canonical_json(report))
                    return 1

                payload, labels = load_export(args.input)
                if not args.confirm:
                    _argument_error(parser, "restore requires --confirm")
                restored = await restore_export(session, labels)
                print(f"restored {restored} labels")
                return 0
            except LabelBackupError as exc:
                _argument_error(parser, str(exc))


def main(argv: Sequence[str] | None = None) -> int:
    """Run the label backup CLI."""
    return asyncio.run(_amain(argv))


if __name__ == "__main__":
    raise SystemExit(main())
